#!/usr/bin/env node
/**
 * Writes src/lib/data/videoManifest.ts — the background clips that really
 * exist on R2. The video registries (surahChapters, surahVerseVideos,
 * quranJuzVideos) name far more clips than were ever rendered: every Surah
 * without a registry entry gets a guessed /videos/surah/NNN-slug.mp4, and
 * Aal-Imran lists 20 chapter clips of which 3 exist. Each of those was a 404 —
 * and the scene kept showing the PREVIOUS Surah's clip over the new image.
 * The app now only asks for clips in this manifest (hasVideo); everything
 * else shows the Surah's image.
 *
 * Run after uploading new clips to R2:
 *   node scripts/tools/video-manifest.mjs          # writes the manifest
 *   node scripts/tools/video-manifest.mjs --check  # exit 1 if it is out of date
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const require = createRequire(import.meta.url);
const OUT = path.join(ROOT, "src/lib/data/videoManifest.ts");
const CHECK = process.argv.includes("--check");

const { nativeFetch } = require(path.join(ROOT, "scripts/qa/lib/load.cjs"));
const { mediaUrl } = require(path.join(ROOT, "src/lib/media.ts"));
const { SURAH_CHAPTERS_REGISTRY, getSurahVisualData } = require(path.join(ROOT, "src/lib/data/surahChapters.ts"));
const { SURAH_VERSE_VIDEOS_REGISTRY } = require(path.join(ROOT, "src/lib/data/surahVerseVideos.ts"));
const { JUZ_VIDEOS } = require(path.join(ROOT, "src/lib/data/quranJuzVideos.ts"));

// Every clip path any resolver can produce (raw "/videos/…" paths).
const candidates = new Set();
const add = (p) => p && p.startsWith("/videos/") && candidates.add(p);
for (let s = 1; s <= 114; s++) {
  const d = SURAH_CHAPTERS_REGISTRY[s] ?? getSurahVisualData(s);
  add(d.masterVideoPath);
  d.chapters.forEach((c) => add(c.videoPath));
}
for (const ayahs of Object.values(SURAH_VERSE_VIDEOS_REGISTRY)) for (const v of Object.values(ayahs)) add(v.videoPath);
for (const j of Object.values(JUZ_VIDEOS)) {
  add(j.videoPath);
  (j.playlist ?? []).forEach(add);
}

const present = [];
const missing = [];
await Promise.all(
  [...candidates].map(async (p) => {
    const res = await nativeFetch(mediaUrl(p), { method: "HEAD" });
    (res.ok ? present : missing).push(p);
  }),
);
present.sort();
missing.sort();

const body = `// GENERATED by scripts/tools/video-manifest.mjs — do not edit by hand.
// The background clips that exist on R2 (${present.length} of the ${candidates.size} the
// video registries name). The app requests only these; any other scene shows
// its image. Re-run the script after uploading clips.

const VIDEOS: ReadonlySet<string> = new Set([
${present.map((p) => `  "${p}",`).join("\n")}
]);

/** True when this raw "/videos/…" path (or its R2 URL) is a clip on R2. */
export function hasVideo(path: string | null | undefined): boolean {
  if (!path) return false;
  const i = path.indexOf("/videos/");
  return i >= 0 && VIDEOS.has(path.slice(i).split("?")[0]);
}
`;

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    console.error("✗ videoManifest.ts is out of date — run node scripts/tools/video-manifest.mjs");
    process.exit(1);
  }
  console.log(`✓ manifest up to date (${present.length} clips)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`Wrote ${path.relative(ROOT, OUT)}: ${present.length} clips on R2, ${missing.length} named but missing:`);
  for (const p of missing) console.log(`  ${p}`);
}
