// Builds src/lib/data/mushafPages.ts — the first ayah that begins on every
// Madinah-Mushaf page (1–604), read from the QPC V4 glyph data
// (public/data/quran-glyphs/, each word carries its page). An ayah's page is
// the page of its first word; every page has at least one ayah beginning on it. Run: node scripts/generation/build-mushaf-pages.mjs
import { readFileSync, writeFileSync } from "node:fs";

const starts = new Map();
for (let s = 1; s <= 114; s++) {
  const verses = JSON.parse(readFileSync(`public/data/quran-glyphs/${s}.json`, "utf8"));
  for (const v of verses) {
    const page = v.w[0][1];
    if (!starts.has(page)) starts.set(page, [s, v.a]);
  }
}
const rows = [];
for (let p = 1; p <= 604; p++) {
  if (!starts.has(p)) throw new Error(`page ${p} has no ayah start`);
  rows.push(starts.get(p));
}
const body = rows.map(([s, a]) => `[${s},${a}]`).join(",");
writeFileSync(
  "src/lib/data/mushafPages.ts",
  `// Generated by scripts/generation/build-mushaf-pages.mjs — do not edit.

/** [surah, ayah] of the first ayah starting on each Madinah-Mushaf page (index = page - 1). */
export const MUSHAF_PAGE_STARTS: ReadonlyArray<readonly [surah: number, ayah: number]> = [${body}];

export const MUSHAF_PAGE_COUNT = 604;

/** Mushaf page an ayah begins on. */
export function mushafPageOf(surah: number, ayah: number): number {
  let lo = 0;
  let hi = MUSHAF_PAGE_STARTS.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    const [s, a] = MUSHAF_PAGE_STARTS[mid];
    if (s < surah || (s === surah && a <= ayah)) lo = mid;
    else hi = mid - 1;
  }
  return lo + 1;
}
`
);
console.log("pages:", rows.length, "p1", rows[0], "p2", rows[1], "p604", rows[603]);
